var updateStableSurface = flag.Bool("update-stable-surface", false, "rewrite docs/stable-surface.md")

// renderStableSurface builds the v1.0 stable-surface inventory (commands,
// flags, personas, config keys, environment variables) from the live command tree and the embedded persona files.
// Hidden commands and flags are deprecated aliases that existing scripts still
// call, so they are listed too and marked deprecated.
func renderStableSurface(root string) string {
	var b strings.Builder
	b.WriteString("# Stable surface\n\n")
	b.WriteString("<!-- GENERATED by cli/stable_surface_test.go. Do not edit by hand;\n")
	b.WriteString("     regenerate with: go test ./cli -run TestStableSurfaceInventory -update-stable-surface -->\n\n")
	b.WriteString("The commands, flags, personas, config keys and environment variables below are the v1.0 compatibility surface.\n\n")

	b.WriteString("## Commands and flags\n\n")
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		fmt.Fprintf(&b, "### `%s`\n\n", c.CommandPath())
		if c.Hidden {
			b.WriteString("Deprecated alias command.\n\n")
		}
		var rows []string
		c.NonInheritedFlags().VisitAll(func(f *pflag.Flag) {
			name := "--" + f.Name
			if f.Shorthand != "" {
				name = "-" + f.Shorthand + ", " + name
			}
			status := ""
			if f.Hidden {
				status = "deprecated alias"
			}
			rows = append(rows, fmt.Sprintf("| `%s` | %s | `%s` | %s |\n", name, f.Value.Type(), f.DefValue, status))
		})
		if len(rows) == 0 {
			b.WriteString("No flags.\n\n")
		} else {
			b.WriteString("| Flag | Type | Default | Status |\n|---|---|---|---|\n")
			sort.Strings(rows)
			for _, r := range rows {
				b.WriteString(r)
			}
			b.WriteString("\n")
		}
		subs := append([]*cobra.Command(nil), c.Commands()...)
		sort.Slice(subs, func(i, j int) bool { return subs[i].Name() < subs[j].Name() })
		for _, s := range subs {
			if s.Name() == "help" || s.Name() == "completion" {
				continue
			}
			walk(s)
		}
	}
	walk(NewRootCmd())

	b.WriteString("## Personas\n\n")
	b.WriteString("| Persona | Kind |\n|---|---|\n")
	for _, n := range personas.Names() {
		fmt.Fprintf(&b, "| `%s` | built-in reviewer |\n", n)
	}
	fmt.Fprintf(&b, "| `%s` | built-in threat mapper |\n", personas.ThreatMapperName)
	for _, n := range personas.CommunityNames() {
		fmt.Fprintf(&b, "| `%s` | community |\n", n)
	}

	b.WriteString("\n## Config keys\n\n")
	b.WriteString("Keys of the user registry (`registry.yaml`) and the project config (`.atcr/config.yaml`). `<name>` is a user-chosen map key.\n\n")
	for _, sec := range []struct {
		title string
		typ   reflect.Type
	}{
		{"Registry (`registry.yaml`)", reflect.TypeOf(registry.Registry{})},
		{"Project config (`.atcr/config.yaml`)", reflect.TypeOf(registry.ProjectConfig{})},
	} {
		fmt.Fprintf(&b, "### %s\n\n| Key | Type |\n|---|---|\n", sec.title)
		keys := map[string]string{}
		collectConfigKeys(sec.typ, "", keys)
		sorted := make([]string, 0, len(keys))
		for k := range keys {
			sorted = append(sorted, k)
		}
		sort.Strings(sorted)
		for _, k := range sorted {
			fmt.Fprintf(&b, "| `%s` | %s |\n", k, keys[k])
		}
		b.WriteString("\n")
	}

	b.WriteString("## Environment variables\n\n")
	b.WriteString("Every `ATCR_*` name read by non-test Go source, with the files that reference it.\n\n")
	b.WriteString("| Variable | Referenced in |\n|---|---|\n")
	env := scanEnvVars(root)
	names := make([]string, 0, len(env))
	for n := range env {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "| `%s` | %s |\n", n, strings.Join(env[n], ", "))
	}
	return b.String()
}

// collectConfigKeys records the Go type of every yaml key reachable from t, walking
// nested structs, pointers, slices and maps (map keys render as <name>).
func collectConfigKeys(t reflect.Type, prefix string, keys map[string]string) {
	for t.Kind() == reflect.Ptr {
		t = t.Elem()
	}
	if t.Kind() != reflect.Struct {
		return
	}
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		tag := f.Tag.Get("yaml")
		name := strings.Split(tag, ",")[0]
		if name == "-" || (tag == "" && !f.Anonymous) || !f.IsExported() {
			continue
		}
		if name == "" {
			continue
		}
		key := prefix + name
		keys[key] = f.Type.String()
		elem := f.Type
		for {
			switch elem.Kind() {
			case reflect.Ptr, reflect.Slice:
				elem = elem.Elem()
				continue
			case reflect.Map:
				key += ".<name>"
				elem = elem.Elem()
				continue
			}
			break
		}
		collectConfigKeys(elem, key+".", keys)
	}
}

var atcrEnvRE = regexp.MustCompile(`"(ATCR_[A-Z0-9_]+)"`)

// scanEnvVars maps each ATCR_* string literal in non-test Go source under root
// to the sorted, repo-relative files that mention it.
func scanEnvVars(root string) map[string][]string {
	out := map[string][]string{}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			if n := d.Name(); n == ".git" || n == ".paperclip" || n == "node_modules" || n == "testdata" {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(root, path)
		rel = filepath.ToSlash(rel)
		seen := map[string]bool{}
		for _, m := range atcrEnvRE.FindAllSubmatch(data, -1) {
			name := string(m[1])
			if !seen[name] {
				seen[name] = true
				out[name] = append(out[name], "`"+rel+"`")
			}
		}
		return nil
	})
	if err != nil {
		panic(err)
	}
	for _, files := range out {
		sort.Strings(files)
	}
	return out
}

// TestStableSurfaceInventory regenerates docs/stable-surface.md and fails on a
// diff, so a flag, command, persona, config key or ATCR_* lookup added without regenerating is caught.
func TestStableSurfaceInventory(t *testing.T) {
	root := repoRootDir(t)
	path := filepath.Join(root, "docs", "stable-surface.md")
	got := renderStableSurface(root)
	if *updateStableSurface {
		require.NoError(t, os.WriteFile(path, []byte(got), 0o644))
		return
	}
	want, err := os.ReadFile(path)
	require.NoError(t, err, "read docs/stable-surface.md")
	require.Equal(t, string(want), got,
		"docs/stable-surface.md is stale; regenerate with: go test ./cli -run TestStableSurfaceInventory -update-stable-surface")
}
