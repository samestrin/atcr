package cli

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"github.com/samestrin/atcr/personas"
	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
	"github.com/stretchr/testify/require"
)

var updateStableSurface = flag.Bool("update-stable-surface", false, "rewrite docs/stable-surface.md")

// renderStableSurface builds the v1.0 stable-surface inventory (commands,
// flags, personas) from the live command tree and the embedded persona files.
// Hidden commands and flags are deprecated aliases that existing scripts still
// call, so they are listed too and marked deprecated.
func renderStableSurface() string {
	var b strings.Builder
	b.WriteString("# Stable surface\n\n")
	b.WriteString("<!-- GENERATED by cli/stable_surface_test.go. Do not edit by hand;\n")
	b.WriteString("     regenerate with: go test ./cli -run TestStableSurfaceInventory -update-stable-surface -->\n\n")
	b.WriteString("The commands, flags and personas below are the v1.0 compatibility surface.\n\n")

	b.WriteString("## Commands and flags\n\n")
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		fmt.Fprintf(&b, "### `%s`\n\n", c.CommandPath())
		if c.Hidden {
			b.WriteString("Deprecated alias command.\n\n")
		}
		var rows []string
		c.NonInheritedFlags().VisitAll(func(f *pflag.Flag) {
			name := "--" + f.Name
			if f.Shorthand != "" {
				name = "-" + f.Shorthand + ", " + name
			}
			status := ""
			if f.Hidden {
				status = "deprecated alias"
			}
			rows = append(rows, fmt.Sprintf("| `%s` | %s | `%s` | %s |\n", name, f.Value.Type(), f.DefValue, status))
		})
		if len(rows) == 0 {
			b.WriteString("No flags.\n\n")
		} else {
			b.WriteString("| Flag | Type | Default | Status |\n|---|---|---|---|\n")
			sort.Strings(rows)
			for _, r := range rows {
				b.WriteString(r)
			}
			b.WriteString("\n")
		}
		subs := append([]*cobra.Command(nil), c.Commands()...)
		sort.Slice(subs, func(i, j int) bool { return subs[i].Name() < subs[j].Name() })
		for _, s := range subs {
			if s.Name() == "help" || s.Name() == "completion" {
				continue
			}
			walk(s)
		}
	}
	walk(NewRootCmd())

	b.WriteString("## Personas\n\n")
	b.WriteString("| Persona | Kind |\n|---|---|\n")
	for _, n := range personas.Names() {
		fmt.Fprintf(&b, "| `%s` | built-in reviewer |\n", n)
	}
	fmt.Fprintf(&b, "| `%s` | built-in threat mapper |\n", personas.ThreatMapperName)
	for _, n := range personas.CommunityNames() {
		fmt.Fprintf(&b, "| `%s` | community |\n", n)
	}
	return b.String()
}

// TestStableSurfaceInventory regenerates docs/stable-surface.md and fails on a
// diff, so a flag, command or persona added without regenerating is caught.
func TestStableSurfaceInventory(t *testing.T) {
	path := filepath.Join(repoRootDir(t), "docs", "stable-surface.md")
	got := renderStableSurface()
	if *updateStableSurface {
		require.NoError(t, os.WriteFile(path, []byte(got), 0o644))
		return
	}
	want, err := os.ReadFile(path)
	require.NoError(t, err, "read docs/stable-surface.md")
	require.Equal(t, string(want), got,
		"docs/stable-surface.md is stale; regenerate with: go test ./cli -run TestStableSurfaceInventory -update-stable-surface")
}
