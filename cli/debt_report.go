// debtReportGeneratedMarker is stamped into every report as its second line. As
// with the dashboard's marker, it is also the proof of authorship --output checks
// before truncating a file: a file without it was not written by the report.
const debtReportGeneratedMarker = "_Generated by `atcr debt report` — do not edit by hand; regenerate to update._"

// debtReportLooseSection heads the records that came from no README section:
// findings reconcile or `debt add` filed rather than `debt import`.
const debtReportLooseSection = "Not from a README section"

func newDebtReportCmd() *cobra.Command {
	cmd := &cobra.Command{
		Use:   "report",
		Short: "Generate the human technical-debt report (Markdown), grouped by README section",
		Long: "atcr debt report renders every item in the local TD store, in every\n" +
			"status, as Markdown tables grouped by the README section `debt import`\n" +
			"read it from, newest section first; items from no README section come\n" +
			"last. The report is marked as generated and carries no timestamp, so\n" +
			"rerunning it on an unchanged store is byte-identical.\n\n" +
			"It writes to stdout by default; --output <file> writes a file instead and\n" +
			"refuses to overwrite one the report did not generate. --check with\n" +
			"--output fails (exit 4) when the file is out of date, as `debt dashboard`\n" +
			"does. Secret-shaped tokens in item text are scrubbed.",
		Args: usageArgs(cobra.NoArgs),
		RunE: runDebtReport,
	}
	addDebtStoreFlag(cmd)
	cmd.Flags().String("format", "md", "output format; md is the only one")
	cmd.Flags().String("output", "", "write to a file instead of stdout")
	cmd.Flags().Bool("check", false, "assert the file at --output matches freshly generated output, exiting non-zero on drift (an assertion against drift, not a --dry-run-style preview)")
	return cmd
}

func runDebtReport(cmd *cobra.Command, _ []string) error {
	if format := mustFlag(cmd, "format"); format != "md" {
		return usageError(fmt.Errorf("invalid --format %q: md is the only format", format))
	}
	out := mustFlag(cmd, "output")
	check, _ := cmd.Flags().GetBool("check")
	if check && out == "" {
		return usageError(errors.New("--check requires --output <file>"))
	}
	// Validated before any read, as the dashboard does: the resolved path is the
	// one validated and the one written.
	outputPath := out
	if out != "" {
		var err error
		if outputPath, err = resolveDashboardOutput(out); err != nil {
			return usageError(err)
		}
		if err := validation.FilePath(outputPath); err != nil {
			return usageError(err)
		}
	}

	dir, err := debtStoreDir(cmd)
	if err != nil {
		return err
	}
	// Every record is rendered, so every record is read; there is no narrower
	// selection to make, unlike the dashboard's top list.
	recs, err := localdebt.ReadAll(dir, localdebt.ReadOpts{Writer: cmd.ErrOrStderr()})
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("read local debt store: %w", localdebt.RedactPathErr(err))
	}
	content := renderDebtReport(localdebt.FoldRecords(recs))

	switch {
	case check:
		return checkGeneratedFile(cmd, outputPath, out, content, "report")
	case out == "":
		_, err := fmt.Fprint(cmd.OutOrStdout(), content)
		return err
	default:
		if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
			return usageError(fmt.Errorf("failed to create the directory for %q: %w", out, localdebt.RedactPathErr(err)))
		}
		if err := writeGeneratedFile(outputPath, content, debtReportGeneratedMarker, "atcr debt report"); err != nil {
			return usageError(fmt.Errorf("failed to write report to %q: %w", out, localdebt.RedactPathErr(err)))
		}
		return nil
	}
}

// debtReportSection is one heading of the report and the records under it.
type debtReportSection struct {
	heading string
	// date is the section's RFC3339 date, empty when its heading has none.
	date string
	recs []localdebt.Record
}

// renderDebtReport renders folded records as Markdown, one table per README
// section. It reads no clock and orders everything by content alone, so the
// same store always renders the same bytes:
//
//   - dated sections newest first, then undated ones, ties by heading;
//   - the records from no section last;
//   - within a section, most severe first, then by file, line and id.
func renderDebtReport(recs []localdebt.Record) string {
	red := log.NewRedactor("") // token scrub only, as the dashboard does
	bySection := map[string]*debtReportSection{}
	var loose []localdebt.Record
	for _, r := range recs {
		heading := ""
		if r.SourceReport != nil {
			heading = debtReportHeading(r.SourceReport.Section)
		}
		if heading == "" {
			loose = append(loose, r)
			continue
		}
		sec := bySection[heading]
		if sec == nil {
			date, _ := importSectionTime(r.SourceReport.Section)
			sec = &debtReportSection{heading: heading, date: date}
			bySection[heading] = sec
		}
		sec.recs = append(sec.recs, r)
	}
	sections := make([]*debtReportSection, 0, len(bySection)+1)
	for _, sec := range bySection {
		sections = append(sections, sec)
	}
	sort.Slice(sections, func(i, j int) bool {
		a, b := sections[i], sections[j]
		if (a.date == "") != (b.date == "") {
			return a.date != ""
		}
		if a.date != b.date {
			return a.date > b.date
		}
		return a.heading < b.heading
	})
	if len(loose) > 0 {
		sections = append(sections, &debtReportSection{heading: debtReportLooseSection, recs: loose})
	}

	var b strings.Builder
	b.WriteString("# Technical Debt Report\n\n")
	b.WriteString(debtReportGeneratedMarker + "\n\n")
	if len(sections) == 0 {
		b.WriteString("_No items._\n")
		return b.String()
	}
	fmt.Fprintf(&b, "**Items:** %d in %d sections\n", len(recs), len(sections))
	for _, sec := range sections {
		sortDebtReportRecords(sec.recs)
		fmt.Fprintf(&b, "\n## %s\n\n", sec.heading)
		b.WriteString("| ID | Status | Severity | File | Problem | Fix | Category | Est Minutes | Attempts |\n")
		b.WriteString("|----|--------|----------|------|---------|-----|----------|-------------|----------|\n")
		for _, r := range sec.recs {
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %d | %d |\n",
				debtMarkdownCell(debtIDCell(r.ID)), debtReportStatus(r.Status),
				debtMarkdownCell(r.Severity), debtMarkdownCell(red.Redact(debtLocation(r))),
				debtMarkdownCell(red.Redact(r.RowProblem())), debtMarkdownCell(red.Redact(r.Fix)),
				debtMarkdownCell(r.Category), r.EstMinutes, r.Attempts)
		}
	}
	return b.String()
}

// debtReportHeading turns a stored `### [date] From: ...` section into the text
// of a report heading: the leading hashes go (the report sets its own level), and
// the text is made safe as debtMarkdownCell makes a cell, except that a pipe is
// kept, since it cannot break a heading.
func debtReportHeading(section string) string {
	s := strings.TrimLeft(strings.TrimSpace(section), "#")
	s = strings.ReplaceAll(s, "\r\n", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	s = sanitizeCell(s)
	s = strings.ReplaceAll(s, "<", "&lt;")
	s = strings.ReplaceAll(s, ">", "&gt;")
	return strings.TrimSpace(log.NewRedactor("").Redact(s))
}

// debtReportStatus names a record's status, with no status read as open.
func debtReportStatus(status string) string {
	s := strings.ToLower(strings.TrimSpace(status))
	if s == "" {
		return "open"
	}
	return debtMarkdownCell(s)
}

func sortDebtReportRecords(recs []localdebt.Record) {
	sort.Slice(recs, func(i, j int) bool {
		a, b := recs[i], recs[j]
		if ra, rb := severityRank(a.Severity), severityRank(b.Severity); ra != rb {
			return ra > rb
		}
		if a.File != b.File {
			return a.File < b.File
		}
		if a.Line != b.Line {
			return a.Line < b.Line
		}
		return a.ID < b.ID
	})
}
